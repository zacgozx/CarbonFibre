import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))
from playwright.sync_api import sync_playwright
# Rubber ducky mode, the interactive part (the rules themselves are in duck_rules_test.py): the panel
# beside the note, clicking to jump, hover highlight, the step under the caret, vim's gd ]] [[ K
# Ctrl+O Ctrl+I and :duck, the palette toggle, and hiding in narrow panes and Source mode.
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-66s %s %s" % (label, "ok" if good else "FAIL", detail))
NOTE = "\n".join(["# Hunt", "", "Export the hosts, then look them up.", "",
  "```python", "import pandas as pd", "df = pd.read_csv('raw.csv')", "spare = 1", "df.query('n > 1').to_csv('hosts.csv')", "```", "",
  "```spl", "| inputlookup hosts", "| stats count by host", "| where status>400", "```", ""])
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1400, "height": 850})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-welcomed', '1'); localStorage.setItem('carbonfibre-v1', s); }",
                json.dumps({"notes": [{"id": 1, "title": "Hunt", "content": NOTE}], "seq": 2}))
    pg.reload(); pg.wait_for_timeout(500)
    E = lambda js, *a: pg.evaluate(js, *a)
    E("() => openInPane(1, panes[0])"); pg.wait_for_timeout(150)
    shown = lambda: E("() => { const d = panes[0].root.querySelector('.duck'); return !!d && !d.hidden; }")
    check("off by default: no panel", not shown())
    E("() => Duck.toggle()"); pg.wait_for_timeout(150)
    check("the palette command turns it on, beside the note", shown() and E("() => panes[0].root.classList.contains('duck-on')"))
    check("...and the choice is kept", E("() => localStorage.getItem('carbonfibre-duck')") == "1")
    txt = lambda: E("() => panes[0].root.querySelector('.duck').textContent")
    check("data flow at the top: Python feeds SPL", "Data flow" in txt() and E("() => [...document.querySelectorAll('.duck-node')].map(x => x.textContent).join()") == "1 Python,2 Splunk SPL", txt()[:200])
    check("one full card (the first block with no caret), the other compact", E("() => [document.querySelectorAll('.duck-card.on').length, document.querySelectorAll('.duck-card').length]") == [1, 2])
    E("() => panes[0].setActive(13, 0)"); pg.wait_for_timeout(150)
    check("the caret in the SPL block: its card is the full one", "Splunk SPL" in E("() => document.querySelector('.duck-card.on .duck-sum').textContent"))
    check("...with the question about status", "status" in E("() => document.querySelector('.duck-card.on .duck-q').textContent"))
    check("...and the step under the caret highlighted", E("() => document.querySelector('.duck-step.cur').dataset.line") == "13")
    E("() => panes[0].setActive(14, 0)"); pg.wait_for_timeout(150)
    check("moving down moves the highlight", E("() => document.querySelector('.duck-step.cur').dataset.line") == "14")
    pg.locator(".duck-q").hover(); pg.wait_for_timeout(50)
    check("hovering a question highlights its line in the note", E("() => panes[0].linesEl.children[14].classList.contains('duck-hl')"))
    pg.locator(".duck-card:not(.on)").click(); pg.wait_for_timeout(150)
    check("clicking another block's card goes there", E("() => panes[0].activeLine") == 5, str(E("() => panes[0].activeLine")))
    check("...and makes it the full card", "Python" in E("() => document.querySelector('.duck-card.on .duck-sum').textContent"))
    check("names with line numbers, unused marked", E("() => { const u = document.querySelector('.duck-sym.unused'); return u && u.textContent.includes('spare') && u.dataset.line === '7'; }"))
    pg.locator(".duck-sym.unused").click(); pg.wait_for_timeout(100)
    check("clicking a name goes to its line", E("() => panes[0].activeLine") == 7)

    print("VIM")
    E("() => { Vim.toggle(); panes[0].setActive(8, 0); }"); pg.wait_for_timeout(100)
    pg.keyboard.press("Escape")
    keys = lambda s: [pg.keyboard.press(k) for k in s]
    keys("]]"); pg.wait_for_timeout(100)
    check("]] goes to the next code block", E("() => panes[0].activeLine") == 12, str(E("() => panes[0].activeLine")))
    keys("[["); pg.wait_for_timeout(100)
    check("[[ goes back to the previous one", E("() => panes[0].activeLine") == 5, str(E("() => panes[0].activeLine")))
    pg.keyboard.press("Control+o"); pg.wait_for_timeout(100)
    check("Ctrl+O goes back along the jumps", E("() => panes[0].activeLine") == 12, str(E("() => panes[0].activeLine")))
    pg.keyboard.press("Control+o"); pg.wait_for_timeout(100)
    check("...again", E("() => panes[0].activeLine") == 8, str(E("() => panes[0].activeLine")))
    pg.keyboard.press("Control+i"); pg.wait_for_timeout(100)
    check("Ctrl+I goes forward", E("() => panes[0].activeLine") == 12, str(E("() => panes[0].activeLine")))
    E("() => { const q = panes[0]; q.setActive(8, 0); q.ta.setSelectionRange(1, 1); }"); keys("gd"); pg.wait_for_timeout(100)
    check("gd on df goes to where it's set", E("() => panes[0].activeLine") == 6, str(E("() => panes[0].activeLine")))
    E("() => { const q = panes[0]; q.setActive(13, 0); q.ta.setSelectionRange(10, 10); }"); keys("K"); pg.wait_for_timeout(100)
    k = E("() => document.getElementById('saveState').textContent")
    check("K on a field: where it comes from and where it goes", k.startswith("count: created by the stats on line 14"), k)
    E("() => Vim.ex(panes[0], 'duck')"); pg.wait_for_timeout(100)
    check(":duck hides the panel", not shown())
    E("() => Vim.ex(panes[0], 'duck')"); pg.wait_for_timeout(100)
    check("...and shows it again", shown())
    E("() => Vim.toggle()")

    print("WHERE IT SHOWS")
    E("() => panes[0].root.querySelector('.md-split').click()"); pg.wait_for_timeout(150)
    check("not in Source mode", not shown())
    E("() => panes[0].root.querySelector('.md-live').click()"); pg.wait_for_timeout(150)
    check("back in Live mode", shown())
    E("() => splitPane(panes[0], 'right', 1)"); pg.set_viewport_size({"width": 1000, "height": 850}); pg.wait_for_timeout(300)
    check("hidden in a pane narrower than 520px (and the editor gets its room back)", not shown() and not E("() => panes[0].root.classList.contains('duck-on')"), str(E("() => panes[0].root.clientWidth")))
    E("() => closePane(panes[1])"); pg.set_viewport_size({"width": 1400, "height": 850}); pg.wait_for_timeout(300)
    check("...and back when it's wide again", shown())
    E("() => { const q = panes[0]; q.setActive(14, 0); }"); pg.keyboard.press("End"); pg.keyboard.type(" AND count>1"); pg.wait_for_timeout(400)
    check("editing redraws the panel (debounced)", "count>1" in txt(), txt()[-200:])
    E("() => Duck.toggle()"); pg.wait_for_timeout(100)
    check("turning it off hides it", not shown() and E("() => localStorage.getItem('carbonfibre-duck')") == "0")
    E("() => openInPane(1, panes[0])"); pg.wait_for_timeout(100)
    hl = E("() => { const l = panes[0].linesEl.children[6]; return [l.textContent, l.querySelectorAll('.tk-str').length, l.querySelectorAll('.tk-com').length]; }")
    check("code blocks: single-quoted strings show as strings, not &#39; and a comment", hl[0].endswith("pd.read_csv('raw.csv')") and hl[1] == 1 and hl[2] == 0, str(hl))
    check("no errors", not errs, errs[:2])
    b.close()
print("ALL PASS" if ok else "FAILURES"); sys.exit(0 if ok else 1)
