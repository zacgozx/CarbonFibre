import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))   # the app under test
import json
from playwright.sync_api import sync_playwright
content = "# Shift log\none\ntwo\nthree\nfour\n- bullet item\n## Heading two"
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-60s %s %s" % (label, "ok" if good else "FAIL", detail))
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1200, "height": 700})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": [{"id": 1, "title": "Shift log", "content": content}], "seq": 2}))
    pg.reload(); pg.wait_for_timeout(500)
    L = lambda: pg.evaluate("() => panes[0].lines.slice()")
    sel = lambda: pg.evaluate("() => { if (!panes[0].allSelected) return ['caret', panes[0].activeLine]; const sp = panes[0].lineSpan(); return [sp.from, sp.to]; }")
    reset = lambda: pg.evaluate("c => { panes[0].clearSelectAll(); panes[0].lines = c.split('\\n'); panes[0].commit(true); panes[0].activeLine = null; panes[0].render(); }", content)
    line = lambda i: pg.locator(".pane-col .editor-inner > div").nth(i)
    print("ONE LINE")
    line(2).click(); pg.keyboard.press("Alt+ArrowUp"); pg.wait_for_timeout(100)
    check("Alt+Up moves the line up; the caret goes with it", L()[1:3] == ["two", "one"] and sel() == ["caret", 1], str(L()[1:3]))
    pg.keyboard.press("Alt+ArrowDown"); pg.keyboard.press("Alt+ArrowDown"); pg.wait_for_timeout(100)
    check("Alt+Down twice: two lines down", L()[1:4] == ["one", "three", "two"] and sel() == ["caret", 3])
    pg.keyboard.press("Control+z"); pg.keyboard.press("Control+z"); pg.keyboard.press("Control+z"); pg.wait_for_timeout(100)
    check("each move is one undo step", L() == content.split("\n"), str(L()[:4]))
    reset(); line(2).click(); pg.keyboard.press("Shift+Alt+ArrowDown"); pg.wait_for_timeout(100)
    check("Shift+Alt+Down duplicates the line below", L()[1:4] == ["one", "two", "two"] and sel() == ["caret", 3])
    pg.keyboard.press("Control+Shift+k"); pg.wait_for_timeout(100)
    check("Ctrl+Shift+K deletes the line", L()[1:4] == ["one", "two", "three"])
    reset(); line(3).click(); pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("Ctrl+Enter makes a plain line a task", L()[3] == "- [ ] three", L()[3])
    pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("again ticks it", L()[3] == "- [x] three")
    pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("again unticks it", L()[3] == "- [ ] three")
    line(5).click(); pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("a bullet becomes a task, keeping its text", L()[5] == "- [ ] bullet item", L()[5])
    reset(); line(2).click(); pg.keyboard.press("Control+]"); pg.wait_for_timeout(100)
    check("Ctrl+] indents the line", L()[2].startswith("  two") or L()[2].startswith("    two"), repr(L()[2]))
    pg.keyboard.press("Control+["); pg.wait_for_timeout(100)
    check("Ctrl+[ takes it back", L()[2] == "two", repr(L()[2]))
    print("HIGHLIGHTED LINES")
    reset(); line(2).click(); pg.keyboard.press("Home"); pg.keyboard.press("Shift+ArrowDown"); pg.keyboard.press("Shift+ArrowDown"); pg.keyboard.press("Shift+ArrowDown"); pg.wait_for_timeout(100)
    pg.keyboard.press("Alt+ArrowUp"); pg.wait_for_timeout(100)
    check("Alt+Up moves the whole highlight up, still highlighted", L()[1:5] == ["two", "three", "four", "one"] and sel() == [1, 3], str(L()[1:5]) + str(sel()))
    pg.keyboard.press("Alt+ArrowDown"); pg.keyboard.press("Alt+ArrowDown"); pg.wait_for_timeout(100)
    check("Alt+Down twice: the block moves down two", L()[1:6] == ["one", "- bullet item", "two", "three", "four"] and sel() == [3, 5], str(L()[1:6]) + str(sel()))
    reset(); line(2).click(); pg.keyboard.press("Home"); pg.keyboard.press("Shift+ArrowDown"); pg.keyboard.press("Shift+ArrowDown"); pg.wait_for_timeout(100)
    pg.keyboard.press("Shift+Alt+ArrowDown"); pg.wait_for_timeout(100)
    check("Shift+Alt+Down duplicates the block; the copy is highlighted", L()[1:6] == ["one", "two", "three", "two", "three"] and sel() == [4, 5], str(L()[1:6]) + str(sel()))
    pg.keyboard.press("Control+Shift+k"); pg.wait_for_timeout(100)
    check("Ctrl+Shift+K deletes the highlighted lines", L()[1:5] == ["one", "two", "three", "four"])
    reset(); line(2).click(); pg.keyboard.press("Home"); pg.keyboard.press("Shift+ArrowDown"); pg.keyboard.press("Shift+ArrowDown"); pg.keyboard.press("Shift+ArrowDown"); pg.wait_for_timeout(80)
    pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("Ctrl+Enter on a highlight: every line becomes a task", L()[2:5] == ["- [ ] two", "- [ ] three", "- [ ] four"] and sel() == [2, 4], str(L()[2:5]))
    pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("again: all ticked", L()[2:5] == ["- [x] two", "- [x] three", "- [x] four"])
    pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(100)
    check("again: all unticked", L()[2:5] == ["- [ ] two", "- [ ] three", "- [ ] four"])
    reset(); line(0).click(); pg.keyboard.press("Control+a"); pg.wait_for_timeout(80)
    pg.keyboard.press("Control+b"); pg.wait_for_timeout(100)
    got = L()
    check("Ctrl+B on a highlight: each line's text bold, prefixes kept", got == ["# **Shift log**", "**one**", "**two**", "**three**", "**four**", "- **bullet item**", "## **Heading two**"], str(got))
    pg.keyboard.press("Control+b"); pg.wait_for_timeout(100)
    check("again removes it", L() == content.split("\n"), str(L()))
    pg.keyboard.press("Control+i"); pg.wait_for_timeout(100)
    check("Ctrl+I: italic, and the lines stay highlighted", L()[1] == "*one*" and L()[5] == "- *bullet item*" and sel() == [0, 6], str(L()[:2]))
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(100)
    check("one undo removes the italics from every line", L() == content.split("\n"))
    reset(); line(2).click(); pg.keyboard.press("Control+l"); pg.wait_for_timeout(80)
    check("Ctrl+L highlights the line", sel() == [2, 2], str(sel()))
    pg.keyboard.press("Control+l"); pg.keyboard.press("Control+l"); pg.wait_for_timeout(80)
    check("pressed again, it grows a line at a time", sel() == [2, 4], str(sel()))
    pg.keyboard.press("Control+c"); pg.wait_for_timeout(50)
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
