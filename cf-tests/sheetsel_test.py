import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))
from playwright.sync_api import sync_playwright
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-64s %s %s" % (label, "ok" if good else "FAIL", detail))
rows = [["Host", "Env", "CPU", "Mem"], ["idx01", "Production", "40", "60"], ["idx02", "Preproduction", "55", "70"], ["sh01", "Production", "20", "30"], ["web01", "Test", "10", "15"], ["Total", "", "=SUM(C2:C5)", "=SUM(D2:D5)"]]
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1400, "height": 800})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": [{"id": 1, "title": "N", "content": "# N"}], "seq": 2}))
    pg.reload(); pg.wait_for_timeout(400)
    E = lambda js, *a: pg.evaluate(js, *a)
    def reset():
        E("rows => { const sh = createSheet('Hosts', JSON.parse(JSON.stringify(rows))); openSheetInPane(panes[0], sh.id); }", rows); pg.wait_for_timeout(250)
    reset()
    th = lambda c: pg.locator(".sheet-wrap.show thead tr:first-child th[data-col='%d']" % c)
    rn = lambda r: pg.locator(".sheet-wrap.show .sh-rownum[data-row='%d']" % r)
    data = lambda: E("() => panes[0].grid.sheet.rows.map(r => r.join('|'))")
    hdr = lambda: E("() => [...document.querySelectorAll('.sheet-wrap.show thead th[data-col].sel')].map(t => +t.dataset.col)")
    print("FILTER")
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='1']").fill("Production"); pg.wait_for_timeout(250)
    vis = E("() => panes[0].grid.view.slice(1).map(r => panes[0].grid.sheet.rows[r][1])")
    check("filter 'Production' leaves out 'Preproduction'", vis == ["Production", "Production"], str(vis))
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='1']").fill("prod*"); pg.wait_for_timeout(250)
    check("'prod*' finds words starting prod (Production, not Preproduction)", E("() => panes[0].grid.view.length - 1") == 2)
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='1']").fill("prod"); pg.wait_for_timeout(250)
    check("'prod' alone is a whole word: nothing matches", E("() => panes[0].grid.view.length - 1") == 0)
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='1']").fill("%prod%"); pg.wait_for_timeout(250)
    check("'%prod%' matches anywhere (Preproduction too)", E("() => panes[0].grid.view.length - 1") == 3)
    pg.locator(".sheet-wrap.show .sh-fclear").first.click(); pg.wait_for_timeout(150)
    E("() => { const g = panes[0].grid; g.snapshot(); ['test', 'testing', 'pretest', 'test server'].forEach((v, i) => { g.sheet.rows[i + 1][3] = v; }); g.changed(); g.render(); }"); pg.wait_for_timeout(150)
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='3']").fill("test"); pg.wait_for_timeout(250)
    shown = E("() => panes[0].grid.view.slice(1).map(r => panes[0].grid.sheet.rows[r][3])")
    check("'test' matches the word test, not testing or pretest", shown == ["test", "test server"], str(shown))
    pg.locator(".sheet-wrap.show .sh-fclear").first.click(); pg.wait_for_timeout(150)
    E("() => { const g = panes[0].grid; ['60', '70', '30', '15'].forEach((v, i) => { g.sheet.rows[i + 1][3] = v; }); g.undo = []; g.changed(); g.render(); }"); pg.wait_for_timeout(150)
    print("SELECTING")
    th(2).click(); pg.wait_for_timeout(100)
    check("clicking a column letter selects the whole column", hdr() == [2] and E("() => { const s = panes[0].grid.selSpan(); return [s.r1, s.r2, s.c1, s.c2]; }") == [0, 5, 2, 2])
    b1 = th(1).bounding_box(); b3 = th(3).bounding_box()
    pg.mouse.move(b1["x"] + 10, b1["y"] + 10); pg.mouse.down(); pg.mouse.move(b3["x"] + 10, b3["y"] + 10, steps=5); pg.mouse.up(); pg.wait_for_timeout(100)
    check("dragging across letters selects several columns", hdr() == [1, 2, 3], str(hdr()))
    th(0).click(); pg.keyboard.down("Shift"); th(2).click(); pg.keyboard.up("Shift"); pg.wait_for_timeout(100)
    check("Shift+click extends the column selection", hdr() == [0, 1, 2], str(hdr()))
    rn(2).click(); pg.keyboard.down("Shift"); rn(4).click(); pg.keyboard.up("Shift"); pg.wait_for_timeout(100)
    check("row numbers: click and Shift+click select rows", E("() => [...document.querySelectorAll('.sheet-wrap.show .sh-rownum.sel')].map(t => +t.dataset.row)") == [2, 3, 4])
    print("DELETING AND INSERTING")
    pg.keyboard.press("Control+-"); pg.wait_for_timeout(150)
    check("Ctrl+- deletes all three selected rows", data() == ["Host|Env|CPU|Mem", "idx01|Production|40|60", "Total||=SUM(C2:C2)|=SUM(D2:D2)"], str(data()))
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    check("one undo brings them all back", len(data()) == 6 and data()[5] == "Total||=SUM(C2:C5)|=SUM(D2:D5)")
    th(3).click(button="right"); pg.wait_for_timeout(120)
    items = E("() => [...document.querySelectorAll('.tab-menu .tab-menu-item span')].map(s => s.textContent)")
    check("right-click a column letter: insert, delete, clear, sort, copy", items == ["Move column left", "Move column right", "Insert column left", "Insert column right", "Delete column", "Clear column", "Sort A \u2192 Z", "Sort Z \u2192 A", "Copy"], str(items))
    pg.locator(".tab-menu-item", has_text="Insert column left").click(); pg.wait_for_timeout(150)
    check("Insert column left: formulas follow (D becomes E)", data()[5] == "Total||=SUM(C2:C5)||=SUM(E2:E5)" and data()[0] == "Host|Env|CPU||Mem", str(data()[5]))
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    th(2).click(button="right"); pg.locator(".tab-menu-item", has_text="Sort Z").click(); pg.wait_for_timeout(150)
    srt = data()
    check("Sort Z -> A from the menu (by CPU, header row kept)", [r.split("|")[2] for r in srt if not r.startswith("Total")][1:5] == ["55", "40", "20", "10"], str(srt))
    check("...the Total row stays at the bottom, its formula intact", srt[-1] == "Total||=SUM(C2:C5)|=SUM(D2:D5)", str(srt[-1]))
    check("...and still adds up (125, no loop)", E("() => panes[0].grid.calc.text(5, 2)") == "125", E("() => panes[0].grid.calc.text(5, 2)"))
    pg.keyboard.press("Control+z"); pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    rn(5).click(button="right"); pg.wait_for_timeout(120)
    check("right-click a row number: row items", E("() => [...document.querySelectorAll('.tab-menu .tab-menu-item span')].map(s => s.textContent)")[:5] == ["Move row up", "Move row down", "Insert row above", "Insert row below", "Delete row"])
    pg.keyboard.press("Escape"); pg.wait_for_timeout(80)
    pg.locator(".sheet-wrap.show td[data-r='1'][data-c='1']").click(); pg.keyboard.press("Control+Space"); pg.wait_for_timeout(100)
    check("Ctrl+Space selects the cell's column", hdr() == [1])
    pg.keyboard.press("Delete"); pg.wait_for_timeout(150)
    check("Delete clears the whole column (the cells, not the column)", [r.split("|")[1] for r in data()] == ["", "", "", "", "", ""] and len(data()[0].split("|")) == 4)
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    pg.locator(".sheet-wrap.show th.sh-all").click(); pg.wait_for_timeout(100)
    check("the corner selects everything", E("() => { const s = panes[0].grid.selSpan(); return [s.r1, s.r2, s.c1, s.c2]; }") == [0, 5, 0, 3])
    th(2).hover(); pg.locator(".sheet-wrap.show .sh-sortbtn[data-sort='2']").click(); pg.wait_for_timeout(150)
    check("the sort button on the letter sorts A -> Z (fresh after undo)", [r.split("|")[2] for r in data() if not r.startswith("Total")][1:5] == ["10", "20", "40", "55"], str([r.split("|")[2] for r in data()]))
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
