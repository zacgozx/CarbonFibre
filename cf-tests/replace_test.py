import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))
import json
from playwright.sync_api import sync_playwright
content = "# Hosts\nidx01 is down, idx01 restarted\n**idx01** bold mention\nIDX01 upper case\nidx011 longer name\nhost-12 and host-7"
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-60s %s %s" % (label, "ok" if good else "FAIL", detail))
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1300, "height": 800})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": [{"id": 1, "title": "Hosts", "content": content}, {"id": 2, "title": "Other", "content": "# Other\nidx01 also here\nnothing"}, {"id": 3, "title": "Third", "content": "no match"}], "seq": 4}))
    pg.reload(); pg.wait_for_timeout(500)
    E = lambda js, *a: pg.evaluate(js, *a)
    L = lambda: E("() => panes[0].lines.slice()")
    reset = lambda: E("c => { panes[0].lines = c.split('\\n'); panes[0].commit(true); panes[0].activeLine = null; panes[0].render(); }", content)
    cnt = lambda: E("() => document.querySelector('.find-count').textContent")
    pg.locator(".pane-col .editor-inner > div").nth(1).click()
    pg.keyboard.press("Control+h"); pg.wait_for_timeout(150)
    check("Ctrl+H opens find with the replace row", E("() => document.querySelector('.find-bar').classList.contains('replacing')"))
    pg.keyboard.type("idx01"); pg.wait_for_timeout(150)
    check("any-case matching by default (5 incl. IDX01 and idx011)", cnt() == "1 of 5", cnt())
    pg.click(".find-opt[data-opt='cs']"); pg.wait_for_timeout(100)
    check("Aa: match case (IDX01 drops out)", cnt() == "1 of 4", cnt())
    pg.click(".find-opt[data-opt='ww']"); pg.wait_for_timeout(100)
    check("ab: whole word (idx011 drops out too)", cnt() == "1 of 3", cnt())
    pg.fill(".find-rep", "IDX-PRD-01"); pg.click(".find-r1"); pg.wait_for_timeout(150)
    check("Replace changes just the current match", L()[1] == "IDX-PRD-01 is down, idx01 restarted", L()[1])
    check("...and moves to the next one", cnt() == "1 of 2", cnt())
    pg.click(".find-r1"); pg.wait_for_timeout(150)
    check("the next is the second on that line", L()[1] == "IDX-PRD-01 is down, IDX-PRD-01 restarted", L()[1])
    pg.click(".find-r1"); pg.wait_for_timeout(150)
    check("a match inside **bold**: the raw text changes, markup kept", L()[2] == "**IDX-PRD-01** bold mention", L()[2])
    pg.keyboard.press("Control+z") if False else None
    reset(); pg.wait_for_timeout(100); E("() => findRun(document.querySelector('.find-in').value)")
    pg.click(".find-rall"); pg.wait_for_timeout(150)
    check("All replaces every match (case + whole word: 3)", cnt() == "Replaced 3" and L()[3] == "IDX01 upper case" and L()[4] == "idx011 longer name", cnt() + " " + str(L()[1:5]))
    pg.locator(".find-in").click(); pg.keyboard.press("Escape"); pg.wait_for_timeout(100)
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    check("one Ctrl+Z undoes the whole Replace all", L() == content.split("\n"), str(L()))
    pg.keyboard.press("Control+h"); pg.wait_for_timeout(100)
    for o in ("cs", "ww"): pg.click(".find-opt[data-opt='%s']" % o)
    pg.click(".find-opt[data-opt='re']"); pg.fill(".find-in", r"host-(\d+)"); pg.wait_for_timeout(150)
    check(".*: regular expressions", cnt() == "1 of 2", cnt())
    pg.fill(".find-rep", "srv$1"); pg.click(".find-rall"); pg.wait_for_timeout(150)
    check("...with $1 groups in the replacement", L()[5] == "srv12 and srv7", L()[5])
    pg.fill(".find-in", "(unclosed"); pg.wait_for_timeout(120)
    check("a broken pattern says so instead of failing", cnt() == "Invalid pattern", cnt())
    pg.locator(".find-in").press("Escape"); pg.wait_for_timeout(100)
    print("ACROSS NOTES")
    pg.keyboard.press("Control+Shift+h"); pg.wait_for_timeout(200)
    check("Ctrl+Shift+H opens the search panel with a replace box", E("() => document.getElementById('viewSearch').offsetParent !== null && !!document.getElementById('searchRep')"))
    pg.fill("#search", "idx01"); pg.fill("#searchRep", "IDX-PRD-01"); pg.wait_for_timeout(300)
    dialogs = []
    pg.once("dialog", lambda d: (dialogs.append(d.message), d.accept()))
    pg.click("#searchRepAll"); pg.wait_for_timeout(300)
    check("it asks first, with the count", dialogs and "Replace 6 matches" in dialogs[0] and "in 2 notes" in dialogs[0], dialogs[0][:70] if dialogs else "no dialog")
    notes = E("() => state.notes.map(n => n.content)")
    check("every note changed (any case, as the search box matches)", "idx01" not in notes[0].lower().replace("idx011", "") and notes[1] == "# Other\nIDX-PRD-01 also here\nnothing" and notes[2] == "no match", str([n[:40] for n in notes]))
    check("the open note shows the change", "IDX-PRD-01" in L()[1], L()[1])
    pg.once("dialog", lambda d: d.dismiss())
    pg.fill("#search", "nothing"); pg.fill("#searchRep", "X"); pg.wait_for_timeout(200); pg.click("#searchRepAll"); pg.wait_for_timeout(200)
    check("cancelling changes nothing", E("() => state.notes[1].content").endswith("nothing"))
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
