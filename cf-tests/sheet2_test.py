import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))   # the app under test
import json, time, random
from playwright.sync_api import sync_playwright
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-64s %s %s" % (label, "ok" if good else "FAIL", detail))
random.seed(4)
first = ["Dawn", "Dale", "Herbert", "Karen", "Edward", "Jane", "Cody", "Tabitha", "Mary", "Shari", "Clinton", "Alexis"]
people = [["Index", "First Name", "Sex", "Email", "Born", "Score"]]
for i in range(1, 41):
    people.append([str(i), first[i % 12], "Male" if i % 3 else "Female", "%s%d@example.%s" % (first[i % 12].lower(), i, "org" if i % 4 else "com"), "19%02d-0%d-1%d" % (40 + i, 1 + i % 9, i % 10), str(random.randint(1, 99))])
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1400, "height": 860})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": [{"id": 1, "title": "N", "content": "# N"}], "seq": 2}))
    pg.reload(); pg.wait_for_timeout(400)
    E = lambda js, *a: pg.evaluate(js, *a)
    E("() => { const sh = createSheet('Calc', [['','',''],['','',''],['','',''],['','','']]); openSheetInPane(panes[0], sh.id); }"); pg.wait_for_timeout(200)
    cell = lambda r, c: pg.locator(".sheet-wrap.show td[data-r='%d'][data-c='%d']" % (r, c))
    print("FORMULAS")
    cell(0, 0).click(); pg.keyboard.type("SUM=(10+12)"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("typing SUM=(10+12) shows 22", cell(0, 0).text_content() == "22")
    cell(0, 0).click(); pg.wait_for_timeout(50)
    check("the formula bar shows what was typed, the address A1", E("() => panes[0].grid.fxIn.value") == "SUM=(10+12)" and E("() => panes[0].grid.addrEl.textContent") == "A1")
    cell(1, 0).click(); pg.keyboard.type("8"); pg.keyboard.press("Enter")
    pg.keyboard.type("=A1+A2"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("=A1+A2 adds the cells (22 + 8 = 30)", cell(2, 0).text_content() == "30")
    cell(1, 0).click(); pg.keyboard.type("10"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("changing A2 recalculates A3 (32)", cell(2, 0).text_content() == "32")
    cell(0, 1).click(); pg.click(".sheet-wrap.show .sh-fxin"); pg.keyboard.type("=AVERAGE(A1:A3)"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("typing in the formula bar sets the cell (=AVERAGE -> 21.333...)", cell(0, 1).text_content() == "21.3333333333")
    cell(1, 1).click(); pg.keyboard.type("=A1/0"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("errors show in the cell, in red (#DIV/0!)", cell(1, 1).text_content() == "#DIV/0!" and "err" in (cell(1, 1).get_attribute("class") or ""))
    cell(2, 1).click(); pg.keyboard.type("=B3"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("a cell referring to itself shows #CYCLE!", cell(2, 1).text_content() == "#CYCLE!")
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(100)
    check("undo removes it", cell(2, 1).text_content() == "")
    pg.mouse.click(10, 10)
    print("FILTERS, TYPES, FIND")
    E("rows => { const sh = createSheet('People', rows); openSheetInPane(panes[0], sh.id); }", people); pg.wait_for_timeout(250)
    types = E("() => [...document.querySelectorAll('.sheet-wrap.show .sh-type')].map(e => e.textContent)")
    check("columns show their type: N number, T text, D date", types == ["N", "T", "T", "T", "D", "N"], str(types))
    check("number columns align right", "num" in (cell(1, 0).get_attribute("class") or ""))
    filt = lambda c: pg.locator(".sheet-wrap.show .sh-filter[data-fc='%d']" % c)
    shown = lambda: E("() => [...document.querySelectorAll('.sheet-wrap.show tbody tr[data-row]')].map(tr => +tr.dataset.row)")
    filt(3).fill("%org"); pg.wait_for_timeout(250)
    v = shown()
    check("%org keeps only emails ending in org; the header row stays", v[0] == 0 and len(v) == 31 and all(people[r][3].endswith("org") for r in v[1:]), "%d rows" % len(v))
    check("row numbers keep their original numbering (gaps)", E("() => [...document.querySelectorAll('.sheet-wrap.show .sh-rownum')].slice(0, 6).map(e => e.textContent)") == ["1", "2", "3", "4", "6", "7"])
    filt(2).fill("=male"); pg.wait_for_timeout(250)
    v = shown()
    check("=male is exact (not Female), combined with %org", all(people[r][2] == "Male" and people[r][3].endswith("org") for r in v[1:]) and len(v) > 1, "%d rows" % len(v))
    check("the status bar says how many show", "showing" in E("() => panes[0].grid.countsEl.textContent"), E("() => panes[0].grid.countsEl.textContent"))
    pg.locator(".sheet-wrap.show .sh-fclear").first.click(); pg.wait_for_timeout(150)
    pg.locator(".sheet-wrap.show .sh-fclear").first.click(); pg.wait_for_timeout(150)
    check("x clears a filter", len(shown()) == 41)
    filt(5).fill(">90"); pg.wait_for_timeout(250)
    check(">90 compares numbers", all(int(people[r][5]) > 90 for r in shown()[1:]))
    filt(5).fill(""); filt(1).fill("~clnt"); pg.wait_for_timeout(250)
    check("~clnt fuzzy-matches Clinton", all(people[r][1] == "Clinton" for r in shown()[1:]) and len(shown()) > 1)
    filt(1).fill(""); pg.wait_for_timeout(250)
    cell(1, 1).click()
    pg.keyboard.press("Control+f"); pg.wait_for_timeout(100)
    check("Ctrl+F in a sheet goes to the sheet's find box", E("() => document.activeElement.classList.contains('sh-find-in')"))
    pg.keyboard.type("karen"); pg.wait_for_timeout(250)
    cnt = E("() => document.querySelector('.sheet-wrap.show .sh-find-count').textContent")
    check("find counts matches and highlights them", cnt.endswith("of 8") and pg.locator(".sheet-wrap.show td.hit").count() >= 7, cnt)
    pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    check("Enter moves to the next match", E("() => document.querySelector('.sheet-wrap.show .sh-find-count').textContent").startswith("2 of"))
    pg.fill(".sheet-wrap.show .sh-find-in", "tbth"); pg.wait_for_timeout(250)
    check("without Fuzzy, 'tbth' finds nothing", E("() => document.querySelector('.sheet-wrap.show .sh-find-count').textContent") == "No matches")
    pg.click(".sheet-wrap.show .sh-fuzzy"); pg.wait_for_timeout(250)
    check("with Fuzzy, 'tbth' finds Tabitha", E("() => document.querySelector('.sheet-wrap.show .sh-find-count').textContent").endswith("of 6"), E("() => document.querySelector('.sheet-wrap.show .sh-find-count').textContent"))
    pg.keyboard.press("Escape")
    cell(1, 5).click(); pg.keyboard.down("Shift"); cell(4, 5).click(); pg.keyboard.up("Shift"); pg.wait_for_timeout(100)
    want = sum(int(people[r][5]) for r in range(1, 5))
    info = E("() => panes[0].grid.infoEl.textContent")
    check("selecting numbers shows Sum, Average, Count", ("Sum %d" % want) in info and "Average" in info and "Count 4" in info, info)
    print("SPEED: 100,000 ROWS")
    t0 = time.time()
    E("""() => { const rows = [['Index', 'Name', 'Sex', 'Email', 'Score']]; const names = ['Dawn', 'Dale', 'Karen', 'Edward', 'Clinton'];
        for (let i = 1; i <= 100000; i++) rows.push([String(i), names[i % 5] + i, i % 3 ? 'Male' : 'Female', 'user' + i + '@example.' + (i % 4 ? 'org' : 'com'), String(i % 97)]);
        const sh = createSheet('Big', rows); window.__t = performance.now(); openSheetInPane(panes[0], sh.id); window.__open = performance.now() - window.__t; }""")
    pg.wait_for_timeout(300)
    print("    open: %.0f ms, rows drawn: %d" % (E("() => window.__open"), E("() => document.querySelectorAll('.sheet-wrap.show tbody tr[data-row]').length")))
    t = E("() => { const g = panes[0].grid, t0 = performance.now(); g.scroll.scrollTop = 1400000; g.renderWindow(false); return performance.now() - t0; }")
    print("    jump to row ~50,000: %.0f ms" % t)
    t = E("() => { const g = panes[0].grid, t0 = performance.now(); g.filters[2] = '=female'; g.computeView(); g.drawn = null; g.renderWindow(true); return [performance.now() - t0, g.view.length]; }")
    print("    exact filter =female (index): %.0f ms -> %d rows" % (t[0], t[1]))
    t = E("() => { const g = panes[0].grid, t0 = performance.now(); g.filters[2] = '=male'; g.computeView(); g.drawn = null; g.renderWindow(true); return [performance.now() - t0, g.view.length]; }")
    print("    second exact filter (index already built): %.0f ms -> %d rows" % (t[0], t[1]))
    t = E("() => { const g = panes[0].grid, t0 = performance.now(); g.filters[2] = ''; g.filters[3] = '%com'; g.computeView(); g.drawn = null; g.renderWindow(true); return [performance.now() - t0, g.view.length]; }")
    print("    pattern filter %%com (scan): %.0f ms -> %d rows" % (t[0], t[1]))
    t = E("() => { const g = panes[0].grid, t0 = performance.now(); g.find.q = 'clinton9999'; g.runFind(); return [performance.now() - t0, g.find.hits.length]; }")
    print("    find across the filtered rows: %.0f ms -> %d hits" % (t[0], t[1]))
    check("100k rows: only the rows on screen are drawn", E("() => document.querySelectorAll('.sheet-wrap.show tbody tr[data-row]').length") < 200)
    pg.screenshot(path="/tmp/cf_test.png")
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
