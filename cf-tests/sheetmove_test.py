import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))
from playwright.sync_api import sync_playwright
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-64s %s %s" % (label, "ok" if good else "FAIL", detail))
ROWS = [["Host", "CPU", "Mem", "Total"], ["idx01", "40", "60", "=B2+C2"], ["idx02", "55", "70", "=B3+C3"], ["sh01", "20", "30", "=B4+C4"], ["Sum", "=SUM(B2:B4)", "=SUM(C2:C4)", "=SUM(D2:D4)"]]
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1400, "height": 800})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": [{"id": 1, "title": "N", "content": "# N"}, {"id": 2, "title": "M", "content": "# M"}], "seq": 3}))
    pg.reload(); pg.wait_for_timeout(400)
    E = lambda js, *a: pg.evaluate(js, *a)
    E("rows => { const sh = createSheet('Hosts', JSON.parse(JSON.stringify(rows))); createSheet('Report', [['Idx02 CPU'], ['=Hosts!B3']]); panes[0].open(2); panes[0].open(1); openSheetInPane(panes[0], sh.id); }", ROWS); pg.wait_for_timeout(300)
    data = lambda: E("() => panes[0].grid.sheet.rows.map(r => r.join('|'))")
    val = lambda r, c: E("a => panes[0].grid.calc.text(a[0], a[1])", [r, c])
    th = lambda c: pg.locator(".sheet-wrap.show thead tr:first-child th[data-col='%d']" % c)
    rn = lambda r: pg.locator(".sheet-wrap.show .sh-rownum[data-row='%d']" % r)
    print("DRAGGING")
    th(2).click(); pg.wait_for_timeout(100)
    b2, b0 = th(2).bounding_box(), th(0).bounding_box()
    pg.mouse.move(b2["x"] + 20, b2["y"] + 10); pg.mouse.down(); pg.mouse.move(b0["x"] + b0["width"] * 0.2, b0["y"] + 10, steps=8); pg.wait_for_timeout(80)
    check("dragging a selected column shows where it will land", E("() => !!document.querySelector('.sheet-wrap.show .sh-dropline')"))
    pg.mouse.up(); pg.wait_for_timeout(200)
    check("...and moves it there (Mem to the front)", data()[0] == "Mem|Host|CPU|Total", data()[0])
    check("...formulas follow: Total is still CPU + Mem", data()[1] == "60|idx01|40|=C2+A2" and val(1, 3) == "100", data()[1])
    check("...the sum row too", data()[4] == "=SUM(A2:A4)|Sum|=SUM(C2:C4)|=SUM(D2:D4)" and val(4, 0) == "160", data()[4])
    check("...and the moved column stays selected", E("() => [...document.querySelectorAll('.sheet-wrap.show thead th[data-col].sel')].map(t => +t.dataset.col)") == [0])
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    check("one undo puts it back", data() == [ "|".join(r) for r in ROWS ])
    check("...including the other sheet's reference it had rewritten", E("() => sheets.find(s => s.title === 'Report').rows[1][0]") == "=Hosts!B3", E("() => sheets.find(s => s.title === 'Report').rows[1][0]"))
    pg.keyboard.press("Control+y"); pg.wait_for_timeout(150)
    check("redo moves both again", data()[0] == "Mem|Host|CPU|Total" and E("() => sheets.find(s => s.title === 'Report').rows[1][0]") == "=Hosts!C3")
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    pg.locator(".sheet-wrap.show td[data-r='1'][data-c='1']").click(); pg.wait_for_timeout(80)
    b1 = th(1).bounding_box(); b3 = th(3).bounding_box()
    pg.mouse.move(b1["x"] + 10, b1["y"] + 10); pg.mouse.down(); pg.mouse.move(b3["x"] + 10, b3["y"] + 10, steps=5); pg.mouse.up(); pg.wait_for_timeout(150)
    check("dragging an unselected header still selects (no move)", data() == ["|".join(r) for r in ROWS] and E("() => [...document.querySelectorAll('.sheet-wrap.show thead th[data-col].sel')].map(t => +t.dataset.col)") == [1, 2, 3])
    rn(3).click(); pg.wait_for_timeout(80)
    r3, r1 = rn(3).bounding_box(), rn(1).bounding_box()
    pg.mouse.move(r3["x"] + 10, r3["y"] + 8); pg.mouse.down(); pg.mouse.move(r1["x"] + 10, r1["y"] + 3, steps=8); pg.mouse.up(); pg.wait_for_timeout(200)
    check("dragging a selected row moves it (sh01 to the top of the data)", [r.split("|")[0] for r in data()] == ["Host", "sh01", "idx01", "idx02", "Sum"], str([r.split("|")[0] for r in data()]))
    check("...its formula follows it (=B2+C2 on its new row)", data()[1] == "sh01|20|30|=B2+C2" and val(1, 3) == "50", data()[1])
    check("...another sheet's reference follows idx02 (Hosts!B3 -> B4)", E("() => sheets.find(s => s.title === 'Report').rows[1][0]") == "=Hosts!B4", E("() => sheets.find(s => s.title === 'Report').rows[1][0]"))
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    print("KEYBOARD AND MENU")
    tabs_before = E("() => panes[0].tabs.length + ':' + panes[0].type")
    pg.locator(".sheet-wrap.show td[data-r='1'][data-c='1']").click(); pg.keyboard.press("Alt+ArrowRight"); pg.wait_for_timeout(150)
    check("Alt+Right moves the selected column right", data()[0] == "Host|Mem|CPU|Total", data()[0])
    check("...and doesn't switch tabs", E("() => panes[0].tabs.length + ':' + panes[0].type") == tabs_before and E("() => panes[0].type") == "sheet")
    pg.keyboard.press("Alt+ArrowLeft"); pg.wait_for_timeout(150)
    check("Alt+Left moves it back", data()[0] == "Host|CPU|Mem|Total")
    pg.locator(".sheet-wrap.show td[data-r='2'][data-c='0']").click(); pg.keyboard.press("Alt+ArrowDown"); pg.wait_for_timeout(150)
    check("Alt+Down moves the row down (idx02 below sh01)", [r.split("|")[0] for r in data()] == ["Host", "idx01", "sh01", "idx02", "Sum"])
    pg.keyboard.press("Alt+ArrowUp"); pg.wait_for_timeout(150)
    th(3).click(button="right"); pg.wait_for_timeout(120)
    items = E("() => [...document.querySelectorAll('.tab-menu .tab-menu-item')].map(b => b.querySelector('span').textContent + (b.disabled ? ' (off)' : ''))")
    check("right-click a column: Move left, Move right (off at the edge)", items[:2] == ["Move column left", "Move column right (off)"], str(items[:3]))
    pg.locator(".tab-menu-item", has_text="Move column left").click(); pg.wait_for_timeout(150)
    check("...Move column left works", data()[0] == "Host|CPU|Total|Mem", data()[0])
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
    print("WITH A FILTER")
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='0']").fill("idx*"); pg.wait_for_timeout(300)
    pg.locator(".sheet-wrap.show td[data-r='1'][data-c='0']").click(); pg.keyboard.press("Alt+ArrowDown"); pg.wait_for_timeout(150)
    check("rows don't move while a filter hides some", [r.split("|")[0] for r in data()] == ["Host", "idx01", "idx02", "sh01", "Sum"])
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
