import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))
from playwright.sync_api import sync_playwright
# Tooltips: quick, with shortcut keys; the next one shows at once; hoverable; Esc closes it; beside the
# left icon bar; readable by screen readers without saying a name twice.
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-66s %s %s" % (label, "ok" if good else "FAIL", detail))
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1300, "height": 800})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("() => { localStorage.clear(); localStorage.setItem('carbonfibre-welcomed', '1'); }")
    pg.reload(); pg.wait_for_timeout(500)
    E = lambda js, *a: pg.evaluate(js, *a)
    tip = lambda: E("() => { const t = document.getElementById('cfTip'); return t.hidden ? null : { text: t.firstChild ? t.firstChild.textContent : '', keys: [...t.querySelectorAll('kbd')].map(k => k.textContent), r: t.getBoundingClientRect().toJSON() }; }")
    check("no browser tooltips left (title attributes became ours)", E("() => [...document.querySelectorAll('[title]')].filter(e => !e.closest('svg')).length") == 0)
    check("...but code can still read and change a title", "Split" in E("() => document.getElementById('btnDual').title"))
    g = pg.locator("#actGraph"); box = g.bounding_box()
    pg.mouse.move(box["x"] + box["width"] / 2, box["y"] + box["height"] / 2); pg.wait_for_timeout(200)
    check("not straight away (a short pause first)", tip() is None)
    pg.wait_for_timeout(450)
    t = tip()
    check("then it shows, with the shortcut as keys", t and t["text"] == "Graph" and t["keys"] == ["Ctrl", "G"], str(t))
    check("in the left icon bar it opens beside the icon, not over the next one", t and t["r"]["left"] >= box["x"] + box["width"], str(t and t["r"]))
    nb = pg.locator("#actLibrary").bounding_box()
    pg.mouse.move(nb["x"] + nb["width"] / 2, nb["y"] + nb["height"] / 2); pg.wait_for_timeout(60)
    t2 = tip()
    check("moving to the next icon shows its tooltip at once", t2 and t2["text"].startswith("All notes"), str(t2))
    pg.mouse.move(t2["r"]["left"] + 6, t2["r"]["top"] + t2["r"]["height"] / 2, steps=4); pg.wait_for_timeout(250)
    check("you can move the pointer onto the tooltip and it stays", tip() is not None)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(80)
    check("Esc closes it", tip() is None)
    d = pg.locator("#btnDual").bounding_box()
    pg.mouse.move(10, 400); pg.wait_for_timeout(1000)
    pg.mouse.move(d["x"] + 10, d["y"] + 10); pg.wait_for_timeout(600)
    t3 = tip()
    check("in the header it opens below the button", t3 and t3["r"]["top"] >= d["y"] + d["height"], str(t3 and t3["r"]))
    pg.mouse.down(); pg.wait_for_timeout(50)
    check("pressing the button closes it", tip() is None)
    pg.mouse.up()
    print("SCREEN READERS")
    check("an icon button with no name takes the tooltip as its name", E("() => document.getElementById('actGraph').getAttribute('aria-label')") == "Graph")
    check("a tooltip that says more becomes the description", E("() => { const b = document.getElementById('btnTheme'), id = b.getAttribute('aria-describedby'); return !!id && document.getElementById(id).textContent === b.title && b.title !== b.getAttribute('aria-label'); }"))
    check("one that repeats the name isn't added again", E("() => { const b = document.getElementById('btnNew'); return !(b.getAttribute('aria-describedby') || '').includes('cfTipD'); }"))
    E("() => document.getElementById('btnTheme').title = 'Changed (Alt+L)'")
    check("changing a title from code updates it", E("() => { const b = document.getElementById('btnTheme'); return document.getElementById(b.getAttribute('aria-describedby')).textContent; }") == "Changed (Alt+L)")
    check("no errors", not errs, errs[:2])
    b.close()
print("ALL PASS" if ok else "FAILURES"); sys.exit(0 if ok else 1)
