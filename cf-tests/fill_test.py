import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))   # the app under test
import json
from playwright.sync_api import sync_playwright
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-64s %s %s" % (label, "ok" if good else "FAIL", detail))
rows = [["Qty", "Price", "Total", "Tax rate", "Month", "Host"], ["2", "10", "=A2*B2", "0.1", "Jan", "host01"]] + [[str(3 + i), str(5 + i), "", "", "", ""] for i in range(8)]
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1400, "height": 860})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": [{"id": 1, "title": "N", "content": "# N"}], "seq": 2}))
    pg.reload(); pg.wait_for_timeout(400)
    E = lambda js, *a: pg.evaluate(js, *a)
    E("rows => { const sh = createSheet('Fill', rows); openSheetInPane(panes[0], sh.id); }", rows); pg.wait_for_timeout(250)
    cell = lambda r, c: pg.locator(".sheet-wrap.show td[data-r='%d'][data-c='%d']" % (r, c))
    raw = lambda r, c: E("p => panes[0].grid.sheet.rows[p[0]][p[1]]", [r, c])
    def drag_handle_to(r, c):
        h = pg.locator(".sheet-wrap.show .sh-handle").bounding_box(); t = cell(r, c).bounding_box()
        pg.mouse.move(h["x"] + 4, h["y"] + 4); pg.mouse.down()
        pg.mouse.move(t["x"] + t["width"] / 2, t["y"] + t["height"] / 2, steps=8); pg.wait_for_timeout(60)
        box = E("() => getComputedStyle(document.querySelector('.sheet-wrap.show .sh-fillbox')).display")
        pg.mouse.up(); pg.wait_for_timeout(150)
        return box
    print("DRAG THE FILL HANDLE")
    cell(1, 2).click(); pg.wait_for_timeout(50)
    check("the handle sits on the selection's corner", E("() => getComputedStyle(document.querySelector('.sheet-wrap.show .sh-handle')).display") == "block")
    box = drag_handle_to(6, 2)
    check("dragging shows a dashed preview of the fill", box == "block")
    check("=A2*B2 dragged down becomes =A3*B3 ... =A7*B7", [raw(r, 2) for r in range(2, 7)] == ["=A%d*B%d" % (r + 1, r + 1) for r in range(2, 7)], str([raw(r, 2) for r in range(2, 7)]))
    check("...and each row shows its own result", [cell(r, 2).text_content() for r in range(1, 7)] == [str(int(rows[r][0]) * int(rows[r][1])) for r in range(1, 7)])
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(100)
    check("one undo removes the whole fill", all(raw(r, 2) == "" for r in range(2, 7)))
    cell(1, 3).click(); pg.keyboard.type("=$D$2*A2"); pg.keyboard.press("Enter"); pg.wait_for_timeout(80)
    cell(1, 3).click(); drag_handle_to(3, 3)
    check("$D$2 stays fixed, A2 moves: =$D$2*A3, =$D$2*A4", [raw(2, 3), raw(3, 3)] == ["=$D$2*A3", "=$D$2*A4"], str([raw(2, 3), raw(3, 3)]))
    pg.keyboard.press("Control+z"); pg.keyboard.press("Control+z"); pg.wait_for_timeout(80)
    cell(1, 4).click(); drag_handle_to(4, 4)
    check("Jan continues Feb, Mar, Apr", [raw(r, 4) for r in range(2, 5)] == ["Feb", "Mar", "Apr"])
    cell(1, 5).click(); drag_handle_to(3, 5)
    check("host01 continues host02, host03", [raw(2, 5), raw(3, 5)] == ["host02", "host03"])
    cell(1, 0).click(); pg.keyboard.down("Shift"); cell(2, 0).click(); pg.keyboard.up("Shift")
    drag_handle_to(1, 4) if False else None
    print("DOUBLE-CLICK, SHORTCUTS")
    E("() => { const g = panes[0].grid; g.sheet.rows.forEach((r, i) => { if (i > 1) { r[2] = ''; } }); g.changed(); g.render(); }")
    cell(1, 2).click(); pg.wait_for_timeout(50)
    pg.locator(".sheet-wrap.show .sh-handle").dblclick(); pg.wait_for_timeout(150)
    check("double-click fills down as far as the data beside it (row 10)", raw(9, 2) == "=A10*B10" and E("() => panes[0].grid.sheet.rows.length") == 10, raw(9, 2))
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(80)
    cell(1, 2).click(); pg.keyboard.down("Shift"); cell(5, 2).click(); pg.keyboard.up("Shift"); pg.keyboard.press("Control+d"); pg.wait_for_timeout(100)
    check("Ctrl+D fills the top cell down through the selection", raw(5, 2) == "=A6*B6")
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(80)
    cell(2, 0).click(); pg.keyboard.down("Shift"); cell(2, 1).click(); pg.keyboard.up("Shift")
    E("() => { const g = panes[0].grid; g.sheet.rows[2][0] = '=ROW_TEST'; }") if False else None
    cell(3, 2).click(); pg.keyboard.down("Shift"); cell(6, 3).click(); pg.keyboard.up("Shift")
    pg.keyboard.type("=A4+B4"); pg.keyboard.press("Control+Enter"); pg.wait_for_timeout(120)
    check("Ctrl+Enter puts the entry in every selected cell, adjusted", [raw(3, 2), raw(6, 2), raw(3, 3), raw(6, 3)] == ["=A4+B4", "=A7+B7", "=B4+C4", "=B7+C7"], str([raw(3, 2), raw(6, 2), raw(3, 3), raw(6, 3)]))
    pg.keyboard.press("Control+z"); pg.wait_for_timeout(80)
    print("WITH A FILTER ON")
    pg.locator(".sheet-wrap.show .sh-filter[data-fc='0']").fill(">5"); pg.wait_for_timeout(250)
    vis = E("() => panes[0].grid.view.slice()")
    cell(vis[1], 2).click(); pg.keyboard.type("=A%d*2" % (vis[1] + 1)); pg.keyboard.press("Enter"); pg.wait_for_timeout(80)
    cell(vis[1], 2).click(); drag_handle_to(vis[3], 2)
    hidden = [r for r in range(vis[1], vis[3] + 1) if r not in vis]
    check("only the rows on show are filled; hidden rows untouched", all(raw(r, 2) == "" for r in hidden) and raw(vis[3], 2) == "=A%d*2" % (vis[3] + 1), "hidden %s" % hidden)
    pg.locator(".sheet-wrap.show .sh-fclear").first.click(); pg.wait_for_timeout(150)
    print("CHEATSHEET")
    pg.click(".sheet-wrap.show .sh-helpbtn"); pg.wait_for_timeout(150)
    check("Functions opens the cheatsheet on the right", E("() => !document.querySelector('.sheet-wrap.show .sh-help').hidden"))
    groups = E("() => [...document.querySelectorAll('.sheet-wrap.show .sh-help-body h4')].map(h => h.textContent)")
    check("grouped: Maths, Statistics, Logic, Text, Lookup, Date, formulas, errors", groups == ["Maths", "Statistics", "Logic", "Text", "Lookup", "Date", "Writing formulas", "Errors"], str(groups))
    pg.fill(".sheet-wrap.show .sh-help-in", "lookup"); pg.wait_for_timeout(100)
    check("search narrows it ('lookup' -> VLOOKUP, MATCH)", E("() => [...document.querySelectorAll('.sheet-wrap.show .sh-fn')].map(b => b.dataset.fn)") == ["VLOOKUP", "MATCH"])
    pg.fill(".sheet-wrap.show .sh-help-in", ""); pg.wait_for_timeout(100)
    cell(8, 3).click(); pg.wait_for_timeout(50)
    pg.locator(".sheet-wrap.show .sh-fn[data-fn='SUM']").click(); pg.wait_for_timeout(100)
    check("clicking SUM starts =SUM() in the formula bar, cursor inside", E("() => { const f = panes[0].grid.fxIn; return f.value + '|' + f.selectionStart + '|' + (document.activeElement === f); }") == "=SUM()|5|true")
    pg.keyboard.type("B2:B9"); pg.keyboard.press("Enter"); pg.wait_for_timeout(120)
    want = sum(int(rows[r][1]) for r in range(1, 9))
    check("finishing it in the formula bar calculates (=SUM(B2:B9))", cell(8, 3).text_content() == str(want), cell(8, 3).text_content())
    pg.reload(); pg.wait_for_timeout(500)
    E("rows => { const sh = createSheet('Again', rows); openSheetInPane(panes[0], sh.id); }", rows); pg.wait_for_timeout(250)
    check("the cheatsheet stays open after a reload", E("() => !document.querySelector('.sheet-wrap.show .sh-help').hidden"))
    pg.screenshot(path="/tmp/cf_test.png")
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
