import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
CF = os.environ.get("CF_HTML", os.path.join(HERE, "..", "CarbonFibre.html"))   # the app under test
import json
from playwright.sync_api import sync_playwright
notes = [{"id": 1, "title": "Morning", "content": "# Morning"}, {"id": 2, "title": "INC0049999 Splunk HEC down", "content": "# INC0049999 Splunk HEC down"}]
ok = True
def check(label, good, detail=""):
    global ok; ok &= bool(good); print("  %-64s %s %s" % (label, "ok" if good else "FAIL", detail))
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1500, "height": 900}, color_scheme="dark")
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file://" + CF)
    pg.evaluate("s => { localStorage.clear(); localStorage.setItem('carbonfibre-v1', s); }", json.dumps({"notes": notes, "seq": 3}))
    pg.reload(); pg.wait_for_timeout(500)
    pg.evaluate("() => { tb.view = 'board'; }")   # these checks are about the board's lanes and cards
    E = lambda js, *a: pg.evaluate(js, *a)
    lane = lambda l: E("l => [...document.querySelectorAll('.tb.show [data-lane=\"' + l + '\"] .tb-card .id')].map(e => e.textContent)", l)
    card = lambda tid: pg.locator(".tb.show .tb-card", has=pg.locator(".id", has_text=tid)).first
    pg.click("#actBoard"); pg.wait_for_timeout(200)
    print("EMPTY AND QUICK ADD")
    check("empty lanes explain what to do", E("() => [...document.querySelectorAll('.tb.show .tb-empty')].map(e => e.textContent)")[0].startswith("Nothing to do"))
    q = pg.locator(".tb.show .tb-quick-in")
    for line in ("INC0048812 Exchange node not reporting to Splunk 45m", "Downtime for payroll batch CHG0031204 20 min", "SCTASK0119 - AppDynamics agent restart", "Write up the shift handover 1.5h", "INC0048812 second task same ticket"):
        q.fill(line); q.press("Enter")
    pg.wait_for_timeout(150)
    got = E("() => tb.tasks.map(t => [t.id, t.name, t.est])")
    check("ticket, name and estimate read from one line", got[0] == ["INC0048812", "Exchange node not reporting to Splunk", 45], str(got[0]))
    check("ticket found anywhere in the line, '20 min' read", got[1] == ["CHG0031204", "Downtime for payroll batch", 20], str(got[1]))
    check("no estimate given: 30 min, dash trimmed", got[2] == ["SCTASK0119", "AppDynamics agent restart", 30], str(got[2]))
    check("no ticket: a plain task, '1.5h' is 90 min", got[3] == ["TASK", "Write up the shift handover", 90], str(got[3]))
    check("the box stays focused for the next one", E("() => document.activeElement.classList.contains('tb-quick-in')"))
    check("cards show the kind in words", E("() => document.querySelector('.tb.show .tb-card .kind').textContent") == "Incident")
    print("BUTTONS")
    (card("INC0048812").hover(), card("INC0048812").locator(".tb-start").click()); pg.wait_for_timeout(150)
    check("Start moves it to Working on and starts CarbonFibre's timer", lane("run") == ["INC0048812"] and E("() => !!timer && !!timer.boardUid"))
    check("the card offers Pause and Done while running", E("() => [...document.querySelectorAll('.tb.show [data-lane=run] .tb-act')].map(b => b.dataset.label)") == ["Pause", "Done", "Link a note", "More"])
    E("() => { timer.startedAt -= 50 * 60000; timerSave(); timerRender(); }"); pg.wait_for_timeout(1100)
    check("over estimate: the card says how far over, in red", E("() => { const t = document.querySelector('.tb.show [data-lane=run] .t'); return t.textContent + '|' + t.classList.contains('over'); }") == "5m over|true")
    check("the header clock says it too", E("() => document.querySelector('.tb.show .tb-est').textContent") == "5 min over the estimate")
    (card("CHG0031204").hover(), card("CHG0031204").locator(".tb-start").click()); pg.wait_for_timeout(150)
    check("starting another sends the first back to To do with its 50 min", E("() => tb.tasks[0].state === 'open' && tb.tasks[0].mins === 50"))
    E("() => { timer.startedAt -= 4 * 60000; timerSave(); }")
    pg.click(".tb.show .tb-hold"); pg.wait_for_timeout(150)
    check("Waiting (header) moves the running task to Waiting", lane("held") == ["CHG0031204"])
    (card("SCTASK0119").hover(), card("SCTASK0119").locator(".tb-todone").click()); pg.wait_for_timeout(150)
    check("Done on a card clears it into Done today", lane("done") == ["SCTASK0119"])
    (card("SCTASK0119").hover(), card("SCTASK0119").locator(".tb-reopen").click()); pg.wait_for_timeout(150)
    check("Reopen brings it back to To do", "SCTASK0119" in lane("open"))
    print("DRAG, EDIT, REMOVE")
    def drag(tid, to_lane):
        E("""a => { const c = [...document.querySelectorAll('.tb.show .tb-card')].find(x => x.querySelector('.id').textContent === a.tid);
            const dt = new DataTransfer(); c.dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: dt }));
            const lane = document.querySelector('.tb.show [data-drop="' + a.lane + '"]'), r = lane.getBoundingClientRect();
            const o = { bubbles: true, cancelable: true, dataTransfer: dt, clientX: r.left + 20, clientY: r.top + 80 };
            lane.dispatchEvent(new DragEvent('dragover', o)); lane.dispatchEvent(new DragEvent('drop', o)); c.dispatchEvent(new DragEvent('dragend', { bubbles: true })); }""", {"tid": tid, "lane": to_lane})
        pg.wait_for_timeout(150)
    drag("SCTASK0119", "held")
    check("dragging a card onto Waiting moves it", "SCTASK0119" in lane("held"))
    drag("SCTASK0119", "run")
    check("dragging onto Working on starts it", lane("run") == ["SCTASK0119"] and E("() => tbRunning().id") == "SCTASK0119")
    drag("SCTASK0119", "done")
    check("dragging the running card to Done stops and clears it", lane("done") == ["SCTASK0119"] and E("() => timer === null"))
    (card("TASK").hover(), card("TASK").locator(".tb-more").click()); pg.wait_for_timeout(100)
    items = E("() => [...document.querySelectorAll('.tb.show .tb-menu-item')].map(b => b.textContent)")
    check("the menu offers Edit, note, move and Remove", items[0] == "Edit" and "Remove" in items and "Create a note for it" in items, str(items))
    pg.locator(".tb.show .tb-menu-item", has_text="Edit").click(); pg.wait_for_timeout(100)
    pg.fill(".tb.show .tb-edit-name", "Write the shift handover"); pg.fill(".tb.show .tb-edit-est", "60"); pg.keyboard.press("Enter"); pg.wait_for_timeout(150)
    check("edit in place: new name and estimate saved", E("() => { const t = tb.tasks.find(t => t.id === 'TASK'); return t.name + '|' + t.est; }") == "Write the shift handover|60")
    card("TASK").locator(".tb-cardtop").dblclick(); pg.wait_for_timeout(100); pg.keyboard.press("Escape"); pg.wait_for_timeout(100)
    check("double-click edits, Esc cancels", E("() => !document.querySelector('.tb.show .tb-edit')"))
    (card("TASK").hover(), card("TASK").locator(".tb-more").click()); pg.locator(".tb.show .tb-menu-item", has_text="Remove").click(); pg.wait_for_timeout(150)
    check("Remove takes it off with no confirm popup, and offers Undo", "TASK" not in lane("open") and E("() => !document.querySelector('.tb.show .tb-undo').hidden"))
    pg.click(".tb.show .tb-undo-btn"); pg.wait_for_timeout(150)
    check("Undo puts it back", "TASK" in lane("open"))
    card("TASK").focus(); pg.keyboard.press("Delete"); pg.wait_for_timeout(100)
    check("Delete on a focused card also removes it (undoable)", "TASK" not in lane("open")); pg.click(".tb.show .tb-undo-btn"); pg.wait_for_timeout(100)
    card("TASK").focus(); pg.keyboard.press("Enter"); pg.wait_for_timeout(150)
    check("Enter on a focused card starts it", lane("run") == ["TASK"])
    print("PERSISTENCE AND SPEC CASES")
    E("() => { timer.startedAt -= 7 * 60000; timerSave(); }"); pg.wait_for_timeout(700)
    pg.reload(); pg.wait_for_timeout(900)
    check("reload mid-task: board back, task still running", E("() => panes.some(q => q.type === 'taskboard')") and lane("run") == ["TASK"])
    check("...clock carried on", E("() => document.querySelector('.tb.show .tb-clock').textContent").startswith("0:07"), E("() => document.querySelector('.tb.show .tb-clock').textContent"))
    E("() => { tb.tasks.find(t => t.state === 'done').clearedAt = '2000-01-01'; tbRenderAll(); }")
    check("after midnight, yesterday's done tasks leave the lane", lane("done") == [])
    E("() => { tbAdd('SCTASK0001', 'Zero estimate', 0); tbRenderAll(); }")
    check("estimate 0: no 'of 0', no bar", E("() => { const c = [...document.querySelectorAll('.tb.show .tb-card')].find(x => x.querySelector('.id').textContent === 'SCTASK0001'); return c.querySelector('.t').textContent === '' && !c.querySelector('.tb-cardbar'); }"))
    E("() => { tbAdd('INC0000001', '<b>bold</b> & a | pipe', 10); tbRenderAll(); }")
    check("names with <b>, & and | stay plain text", E("() => { const n = [...document.querySelectorAll('.tb.show .name')].find(e => e.textContent.includes('pipe')); return n.textContent === '<b>bold</b> & a | pipe' && !n.querySelector('b'); }"))
    E("() => { for (let i = 0; i < 200; i++) tb.tasks.push({ uid: 'bulk' + i, id: 'RITM' + (100000 + i), type: 'ritm', name: 'Bulk ' + i, noteId: null, mins: 0, est: 10, state: 'held', clearedAt: null }); tbRenderAll(); }"); pg.wait_for_timeout(200)
    sc = E("() => { const h = document.querySelector('.tb.show [data-lane=held]'), bd = document.querySelector('.tb.show .tb-board'); return h.scrollHeight > h.clientHeight && bd.scrollHeight <= bd.clientHeight + 1; }")
    check("200 cards in Waiting: that lane scrolls, the board doesn't", sc)
    print("  errors:", errs or "none"); ok &= not errs
    b.close()
print("ALL PASS" if ok else "FAILURES")
